-- De tabellen van server/migraties/0001_meldingen.sql voor Postgres (bijvoorbeeld Supabase,
-- Railway of Render). Tijden zijn milliseconden sinds 1970, dus BIGINT.
CREATE TABLE IF NOT EXISTS meldingen (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  lat DOUBLE PRECISION NOT NULL,
  lon DOUBLE PRECISION NOT NULL,
  koers INTEGER,
  gemaakt BIGINT NOT NULL,
  verloopt BIGINT NOT NULL,
  ja INTEGER NOT NULL DEFAULT 0,
  nee INTEGER NOT NULL DEFAULT 0,
  laatste_ja BIGINT,
  melder TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS meldingen_plek ON meldingen (lat, lon);
CREATE INDEX IF NOT EXISTS meldingen_verloopt ON meldingen (verloopt);
CREATE TABLE IF NOT EXISTS stemmen (
  melding BIGINT NOT NULL,
  toestel TEXT NOT NULL,
  ja INTEGER NOT NULL,
  t BIGINT NOT NULL,
  PRIMARY KEY (melding, toestel)
);
CREATE TABLE IF NOT EXISTS acties (
  soort TEXT NOT NULL,
  toestel TEXT NOT NULL,
  vinger TEXT NOT NULL,
  t BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS acties_toestel ON acties (soort, toestel, t);
CREATE INDEX IF NOT EXISTS acties_vinger ON acties (soort, vinger, t);
CREATE TABLE IF NOT EXISTS zout (
  dag TEXT PRIMARY KEY,
  waarde TEXT NOT NULL
);
-- Supabase zet tabellen in het schema public ook open voor de browser-API. De server praat
-- rechtstreeks met de database als eigenaar van de tabellen; RLS zonder regels houdt de
-- browser-API buiten (de eigenaar merkt er niets van).
ALTER TABLE meldingen ENABLE ROW LEVEL SECURITY;
ALTER TABLE stemmen ENABLE ROW LEVEL SECURITY;
ALTER TABLE acties ENABLE ROW LEVEL SECURITY;
ALTER TABLE zout ENABLE ROW LEVEL SECURITY;
